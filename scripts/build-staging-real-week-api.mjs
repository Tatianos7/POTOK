import {build} from 'esbuild';
import {readFileSync, writeFileSync} from 'node:fs';

const result = await build({entryPoints: ['src/server/stagingRealWeekApiV1.ts'], bundle: true,
  platform: 'node', target: 'node24', format: 'esm', write: false, legalComments: 'none'});
const content = '// Generated by scripts/build-staging-real-week-api.mjs; no private catalog included.\n' + result.outputFiles[0].text;
const output = 'api/staging-real-week.js';
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== content) throw Error('STALE_STAGING_REAL_WEEK_API');
} else writeFileSync(output, content);
